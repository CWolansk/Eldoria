function stripQuotes(value) {
  return String(value || '').trim().replace(/^['"]|['"]$/g, '');
}

function parseScalar(rawValue) {
  const value = stripQuotes(rawValue);
  if (value === '') return '';
  if (value === '[]') return [];
  if (/^\[(.*)\]$/.test(value)) {
    return value
      .slice(1, -1)
      .split(',')
      .map((item) => stripQuotes(item))
      .filter(Boolean);
  }
  if (value === 'true') return true;
  if (value === 'false') return false;
  return value;
}

function parseFrontmatterFallback(content) {
  const match = String(content || '').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, content: String(content || '') };

  const data = {};
  let currentKey = null;

  for (const rawLine of match[1].split(/\r?\n/)) {
    const listMatch = rawLine.match(/^\s+-\s+(.*)$/);
    if (listMatch && currentKey) {
      if (!Array.isArray(data[currentKey])) data[currentKey] = [];
      data[currentKey].push(parseScalar(listMatch[1]));
      continue;
    }

    const kvMatch = rawLine.match(/^([A-Za-z0-9_-]+)\s*:\s*(.*)$/);
    if (kvMatch) {
      currentKey = kvMatch[1];
      data[currentKey] = parseScalar(kvMatch[2]);
    }
  }

  return {
    data,
    content: String(content || '').slice(match[0].length)
  };
}

function parseMarkdown(content) {
  if (grayMatter) return grayMatter(content);
  return parseFrontmatterFallback(content);
}

function escapeHtml(value) {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escapeAttribute(value) {
  return escapeHtml(value).replace(/`/g, '&#96;');
}

function toArray(value) {
  if (!value) return [];
  return Array.isArray(value) ? value.filter(Boolean) : [value].filter(Boolean);
}

function titleFromBody(body) {
  const match = String(body || '').match(/^\s*#\s+(.+)$/m);
  return match ? match[1].trim() : '';
}

function inferType(publicRel, frontmatterType) {
  if (frontmatterType) return String(frontmatterType);

  const parts = toPosix(publicRel).split('/');
  if (parts[0] === 'Storylines') return 'Storyline';
  if (parts[0] === 'Players') return 'Player';
  if (parts[0] !== 'World') return 'Page';
  if (parts[1] === 'Groups') return 'Organization';
  if (parts[1] === 'Events') return 'Event';
  if (parts[1] === 'Items') return 'Item';
  if (parts[1] === 'Images') return 'Reference';
  if (parts.includes('NPCs')) return 'NPC';

  const fileStem = path.posix.basename(publicRel, '.md');
  if (parts.length === 3 && fileStem.toLowerCase() === parts[1].toLowerCase()) return 'Region';
  if (parts.length >= 4 && fileStem.toLowerCase() === parts[2].toLowerCase()) return 'Settlement';
  return 'Location';
}

function inferRegion(publicRel, fm) {
  if (fm.region) return fm.region;
  const parts = toPosix(publicRel).split('/');
  return parts[0] === 'World' && parts.length > 1 ? parts[1] : '';
}

function inferLocation(publicRel, fm, type) {
  if (fm.location) return fm.location;
  if (fm.headquarters) return fm.headquarters;
  const parts = toPosix(publicRel).split('/');
  if (parts[0] === 'World' && parts.length > 3 && !['Groups', 'Events', 'Items', 'Images'].includes(parts[1])) {
    return type === 'Region' ? '' : parts[2];
  }
  return '';
}

function stripUnsupportedBlocks(markdown) {
  let body = String(markdown || '');
  body = body.replace(/```(?:dataview|dataviewjs|custom-frames)[\s\S]*?```/gi, '');
  body = body.replace(/\n{3,}/g, '\n\n');
  body = body.replace(/(?:\n|^)---\s*$/g, '');
  return body.trim();
}

function stripLeadingTitle(markdown, title) {
  const lines = String(markdown || '').split(/\r?\n/);
  const firstContentIndex = lines.findIndex((line) => line.trim() !== '');
  if (firstContentIndex < 0) return markdown;

  const heading = lines[firstContentIndex].match(/^#\s+(.+)$/);
  if (heading && heading[1].trim().toLowerCase() === String(title || '').trim().toLowerCase()) {
    lines.splice(firstContentIndex, 1);
  }

  return lines.join('\n').trim();
}

function inlineMarkdown(value) {
  const placeholders = [];
  let text = String(value || '');

  text = text.replace(/`([^`]+)`/g, (_match, code) => {
    const token = `@@CODE${placeholders.length}@@`;
    placeholders.push(`<code>${escapeHtml(code)}</code>`);
    return token;
  });

  text = escapeHtml(text);

  text = text.replace(/!\[([^\]]*)\]\(([^)]+)\)/g, (_match, alt, href) => {
    return `<img src="${escapeAttribute(href)}" alt="${escapeAttribute(alt)}">`;
  });
  text = text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_match, label, href) => {
    return `<a href="${escapeAttribute(href)}">${label}</a>`;
  });
  text = text.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  text = text.replace(/\*([^*]+)\*/g, '<em>$1</em>');

  placeholders.forEach((html, index) => {
    text = text.replace(`@@CODE${index}@@`, html);
  });

  return text;
}

function renderTable(lines) {
  const rows = lines
    .filter((line, index) => index !== 1)
    .map((line) => line.trim().replace(/^\||\|$/g, '').split('|').map((cell) => cell.trim()));
  const [headers, ...bodyRows] = rows;

  return [
    '<div class="data-table-wrap">',
    '<table class="data-table">',
    '<thead><tr>',
    headers.map((header) => `<th>${inlineMarkdown(header)}</th>`).join(''),
    '</tr></thead>',
    '<tbody>',
    bodyRows.map((row) => `<tr>${row.map((cell) => `<td>${inlineMarkdown(cell)}</td>`).join('')}</tr>`).join('\n'),
    '</tbody>',
    '</table>',
    '</div>'
  ].join('');
}

function collectUntil(lines, start, predicate) {
  const collected = [];
  let index = start;
  while (index < lines.length && predicate(lines[index], index)) {
    collected.push(lines[index]);
    index += 1;
  }
  return { collected, nextIndex: index };
}

function renderMarkdownFallback(markdown) {
  const lines = String(markdown || '').replace(/\r\n/g, '\n').split('\n');
  const html = [];
  let index = 0;

  while (index < lines.length) {
    const line = lines[index];
    const trimmed = line.trim();

    if (!trimmed) {
      index += 1;
      continue;
    }

    if (/^```/.test(trimmed)) {
      const language = trimmed.replace(/^```/, '').trim();
      const collected = [];
      index += 1;
      while (index < lines.length && !/^```/.test(lines[index].trim())) {
        collected.push(lines[index]);
        index += 1;
      }
      index += 1;
      html.push(`<pre class="code-block"><code${language ? ` class="language-${escapeAttribute(language)}"` : ''}>${escapeHtml(collected.join('\n'))}</code></pre>`);
      continue;
    }

    if (/^#{1,6}\s+/.test(trimmed)) {
      const [, marks, label] = trimmed.match(/^(#{1,6})\s+(.+)$/);
      const level = Math.min(marks.length, 3);
      html.push(`<h${level} id="${escapeAttribute(slugifySegment(label))}">${inlineMarkdown(label)}</h${level}>`);
      index += 1;
      continue;
    }

    if (/^---+$/.test(trimmed)) {
      html.push('<hr>');
      index += 1;
      continue;
    }

    if (/^\|.*\|$/.test(trimmed) && lines[index + 1] && /^\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?$/.test(lines[index + 1].trim())) {
      const table = collectUntil(lines, index, (candidate) => /^\|.*\|$/.test(candidate.trim()));
      html.push(renderTable(table.collected));
      index = table.nextIndex;
      continue;
    }

    if (/^>\s?/.test(trimmed)) {
      const block = collectUntil(lines, index, (candidate) => /^>\s?/.test(candidate.trim()));
      const content = block.collected.map((candidate) => candidate.replace(/^>\s?/, '')).join('\n');
      html.push(`<blockquote>${renderMarkdownFallback(content)}</blockquote>`);
      index = block.nextIndex;
      continue;
    }

    if (/^[-*]\s+/.test(trimmed)) {
      const list = collectUntil(lines, index, (candidate) => /^[-*]\s+/.test(candidate.trim()));
      html.push(`<ul>${list.collected.map((item) => `<li>${inlineMarkdown(item.trim().replace(/^[-*]\s+/, ''))}</li>`).join('')}</ul>`);
      index = list.nextIndex;
      continue;
    }

    if (/^\d+\.\s+/.test(trimmed)) {
      const list = collectUntil(lines, index, (candidate) => /^\d+\.\s+/.test(candidate.trim()));
      html.push(`<ol>${list.collected.map((item) => `<li>${inlineMarkdown(item.trim().replace(/^\d+\.\s+/, ''))}</li>`).join('')}</ol>`);
      index = list.nextIndex;
      continue;
    }

    const paragraph = collectUntil(lines, index, (candidate) => {
      const t = candidate.trim();
      return t && !/^(```|#{1,6}\s+|---+$|>\s?|[-*]\s+|\d+\.\s+|\|.*\|$)/.test(t);
    });
    html.push(`<p>${inlineMarkdown(paragraph.collected.map((item) => item.trim()).join(' '))}</p>`);
    index = paragraph.nextIndex;
  }

  return html.join('\n');
}

function renderMarkdown(markdown) {
  if (markedParse) {
    const rendered = markedParse.parse ? markedParse.parse(markdown) : markedParse(markdown);
    return decorateGeneratedHtml(rendered);
  }
  return decorateGeneratedHtml(renderMarkdownFallback(markdown));
}

function decorateGeneratedHtml(html) {
  let output = String(html || '');
  if (output.includes('<table>')) {
    output = output.replace(/<table>/g, '<div class="data-table-wrap"><table class="data-table">');
    output = output.replace(/<\/table>/g, '</table></div>');
  }
  output = output.replace(/<pre><code/g, '<pre class="code-block"><code');
  output = output.replace(/<img /g, '<img class="generated-inline-image" ');
  return output;
}

function applyTemplate(template, context) {
  return template.replace(/\{\{([A-Za-z0-9_]+)\}\}/g, (_match, key) => {
    return Object.prototype.hasOwnProperty.call(context, key) ? String(context[key]) : '';
  });
}

function loadTemplates() {
  const names = [
    'base',
    'default',
    'settlement',
    'npc',
    'shop',
    'landmark',
    'region',
    'organization',
    'group',
    'storyline'
  ];
  const templates = {};
  for (const name of names) {
    templates[name] = fs.readFileSync(path.join(TEMPLATE_DIR, `${name}.html`), 'utf8');
  }
  return templates;
}

function loadPlayerPageMap() {
  if (!fs.existsSync(PLAYER_PAGE_MAP_PATH)) return {};
  try {
    const payload = JSON.parse(fs.readFileSync(PLAYER_PAGE_MAP_PATH, 'utf8'));
    return payload && typeof payload === 'object' && payload.pages && typeof payload.pages === 'object'
      ? payload.pages
      : {};
  } catch (error) {
    throw new Error(`Unable to read player page map at ${PLAYER_PAGE_MAP_PATH}: ${error.message}`);
  }
}

function templateNameForType(type) {
  const key = String(type || '').toLowerCase();
  if (key === 'store' || key === 'shop') return 'shop';
  if (key === 'location' || key === 'landmark') return 'landmark';
  if (key === 'organization') return 'organization';
  if (key === 'group') return 'group';
  if (key === 'storyline') return 'storyline';
  if (['settlement', 'npc', 'region'].includes(key)) return key;
  return 'default';
}

function toneForType(type) {
  const key = String(type || '').toLowerCase();
  if (key === 'npc') return 'npc-card';
  if (key === 'settlement') return 'settlement-card';
  if (key === 'store' || key === 'shop') return 'shop-card';
  if (key === 'location' || key === 'region') return 'location-card';
  return '';
}

function buildPageContext(entry) {
  const raw = fs.readFileSync(entry.fullPath, 'utf8');
  const parsed = parseMarkdown(raw);
  const fm = parsed.data || {};
  const type = inferType(entry.publicRel, fm.type);
  const fallbackTitle = path.basename(entry.publicRel, '.md');
  const title = type === 'Player'
    ? (fm.name || fallbackTitle.replace(/\s+Player Sheet$/i, ''))
    : (fm.name || titleFromBody(parsed.content) || fallbackTitle);

  return {
    ...entry,
    raw,
    body: parsed.content,
    fm,
    title,
    type,
    typeSlug: slugifySegment(type),
    region: inferRegion(entry.publicRel, fm),
    location: inferLocation(entry.publicRel, fm, type),
    tags: toArray(fm.tags)
  };
}

function relativeBreadcrumbHref(fromOutputRel, href) {
  const value = String(href || '');
  if (!value || /^([a-z][a-z0-9+.-]*:|#)/i.test(value)) return value;

  const hashIndex = value.indexOf('#');
  const target = hashIndex >= 0 ? value.slice(0, hashIndex) : value;
  const hash = hashIndex >= 0 ? value.slice(hashIndex) : '';
  return `${relativeHref(fromOutputRel, target)}${hash}`;
}

function buildBreadcrumbItems(page, publicMap) {
  const parts = toPosix(page.publicRel).replace(/\.md$/i, '').split('/');
  const crumbs = [
    { label: 'Home', href: 'index.html' }
  ];

  if (parts[0] === 'Storylines') {
    crumbs.push({ label: 'Storylines', href: 'index.html#storylines' });
  } else if (parts[0] === 'Players') {
    crumbs.push({ label: 'Players', href: 'players.html' });
  } else if (parts[0] === 'World') {
    crumbs.push({ label: 'World', href: 'tools/location-reference.html' });
    const isRegionPage = parts.length === 3 && parts[2]?.toLowerCase() === parts[1]?.toLowerCase();
    if (parts[1]) {
      const regionPage = publicMap.pagesByNoExt.get(`world/${parts[1]}/${parts[1]}`.toLowerCase()) ||
        publicMap.pagesByNoExt.get(`world/${parts[1]}`.toLowerCase());
      crumbs.push({ label: parts[1], href: regionPage ? regionPage.outputRel : '' });
    }
    if (parts[2] && !isRegionPage && !['Groups', 'Events', 'Items', 'Images'].includes(parts[1])) {
      const settlementPage = publicMap.pagesByNoExt.get(`world/${parts[1]}/${parts[2]}/${parts[2]}`.toLowerCase());
      crumbs.push({ label: parts[2], href: settlementPage ? settlementPage.outputRel : '' });
    } else if (parts[2] && parts.length > 3) {
      crumbs.push({ label: parts[2] });
    }
    for (let i = 3; i < parts.length - 1; i += 1) {
      crumbs.push({ label: parts[i] });
    }
  }

  const currentLabel = String(page.title || '').trim();
  const lastCrumb = crumbs[crumbs.length - 1];
  if (lastCrumb && lastCrumb.label.toLowerCase() === currentLabel.toLowerCase()) {
    lastCrumb.href = '';
  } else {
    crumbs.push({ label: page.title });
  }
  return crumbs;
}

function buildBreadcrumbs(page, publicMap) {
  const crumbs = buildBreadcrumbItems(page, publicMap);

  return `<nav class="breadcrumbs" aria-label="Breadcrumbs">${crumbs.map((crumb, index) => {
    const prefix = index > 0 ? '<span>/</span>' : '';
    const href = relativeBreadcrumbHref(page.outputRel, crumb.href);
    const body = href ? `<a href="${escapeAttribute(href)}">${escapeHtml(crumb.label)}</a>` : `<span>${escapeHtml(crumb.label)}</span>`;
    return `${prefix}${body}`;
  }).join('')}</nav>`;
}

function buildBreadcrumbJson(page, publicMap) {
  return escapeAttribute(JSON.stringify(buildBreadcrumbItems(page, publicMap)));
}

function navSectionForPage(page) {
  const root = toPosix(page.publicRel).split('/')[0];
  if (root === 'World') return 'world';
  if (root === 'Storylines') return 'storylines';
  if (root === 'Players') return 'players';
  return '';
}

function buildMetaList(page) {
  const fm = page.fm;
  const fields = [
    ['Type', page.type],
    ['Region', page.region],
    ['Location', page.location],
    ['Status', fm.status],
    ['Profession', fm.profession],
    ['Race', fm.race],
    ['Settlement Type', fm.settlement_type],
    ['Population', fm.population],
    ['Store Type', fm.store_type],
    ['Organization Type', fm.org_type],
    ['Headquarters', fm.headquarters],
    ['Date', fm['fc-date']]
  ].filter(([, value]) => value !== undefined && value !== null && String(value).trim() !== '');

  if (fields.length === 0) return '';

  return `<dl class="entity-meta">${fields.map(([label, value]) => (
    `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`
  )).join('')}</dl>`;
}

function buildTagChips(tags) {
  if (!tags.length) return '';
  return `<div class="chip-row">${tags.map((tag) => `<span class="chip">${escapeHtml(tag)}</span>`).join('')}</div>`;
}

function linkList(title, pages, currentOutputRel) {
  const unique = [...new Map(pages.map((page) => [page.publicRel, page])).values()];
  if (unique.length === 0) return '';

  return [
    '<section class="sheet-panel generated-link-panel">',
    `<div class="sheet-panel-header"><h2>${escapeHtml(title)}</h2></div>`,
    '<ul class="generated-link-list">',
    unique
      .sort((a, b) => (a.title || a.publicRel).localeCompare(b.title || b.publicRel))
      .map((page) => (
        `<li><a href="${escapeAttribute(relativeHref(currentOutputRel, page.outputRel))}">${escapeHtml(page.title || path.basename(page.publicRel, '.md'))}</a>` +
        `${page.type ? `<span class="badge">${escapeHtml(page.type)}</span>` : ''}</li>`
      ))
      .join(''),
    '</ul>',
    '</section>'
  ].join('');
}

function buildSidebar(page, mentions) {
  const sections = [
    linkList('Linked Notes', page.outboundPages || [], page.outputRel),
    linkList('Mentioned In', mentions || [], page.outputRel)
  ].filter(Boolean);

  if (sections.length === 0) return '';
  return `<aside class="generated-sidebar">${sections.join('')}</aside>`;
}

function cleanGeneratedDir(dir) {
  const resolved = path.resolve(dir);
  if (!isInside(DOCS_DIR, resolved) || resolved === DOCS_DIR) {
    throw new Error(`Refusing to clean unsafe output directory: ${resolved}`);
  }
  if (!fs.existsSync(resolved)) {
    ensureDirSync(resolved);
    return;
  }

  for (const item of fs.readdirSync(resolved)) {
    fs.rmSync(path.join(resolved, item), { recursive: true, force: true });
  }
}

function cleanGeneratedFiles(dir) {
  const resolved = path.resolve(dir);
  if (!isInside(DOCS_DIR, resolved) || resolved === DOCS_DIR) {
    throw new Error(`Refusing to clean unsafe output directory: ${resolved}`);
  }
  ensureDirSync(resolved);

  for (const item of fs.readdirSync(resolved)) {
    const fullPath = path.join(resolved, item);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      cleanGeneratedFiles(fullPath);
    } else {
      fs.rmSync(fullPath, { force: true });
    }
  }
}

function assertNoPrivateSourceLinks(entries) {
  const problems = [];
  for (const entry of entries) {
    const content = fs.readFileSync(entry.fullPath, 'utf8');
    problems.push(...findForbiddenPrivateRefs(content, entry.publicRel));
  }
  if (problems.length > 0) {
    throw new Error(`Private references found in public markdown:\n${problems.join('\n')}`);
  }
}

function copyGeneratedAssets(publicMap) {
  cleanGeneratedFiles(GENERATED_ASSET_DIR);
  let copied = 0;
  for (const asset of publicMap.assets) {
    if (/^Players\//i.test(asset.publicRel)) {
      continue;
    }
    const outputPath = path.join(DOCS_DIR, ...asset.outputRel.split('/'));
    ensureDirSync(path.dirname(outputPath));
    fs.copyFileSync(asset.fullPath, outputPath);
    copied += 1;
  }
  return copied;
}

