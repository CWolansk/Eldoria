function writePage(page, html) {
  const outputPath = path.join(DOCS_DIR, ...page.outputRel.split('/'));
  if (!isInside(DOCS_DIR, outputPath)) {
    throw new Error(`Refusing to write outside docs: ${outputPath}`);
  }
  ensureDirSync(path.dirname(outputPath));
  fs.writeFileSync(outputPath, `${GENERATED_HEADER}\n${html.trim()}\n`, 'utf8');
}

function generate() {
  console.log('Scanning Public markdown...');
  const publicMap = buildPublicPathMap(PUBLIC_DIR);
  assertNoPrivateSourceLinks(publicMap.markdownPages);

  const templates = loadTemplates();
  const playerPageMap = loadPlayerPageMap();
  const pages = publicMap.markdownPages.map(buildPageContext);
  const pageByRel = new Map(pages.map((page) => [page.publicRel, page]));

  for (const entry of publicMap.markdownPages) {
    const page = pageByRel.get(entry.publicRel);
    entry.title = page.title;
    entry.type = page.type;
  }

  const mentionsByPublicRel = new Map();
  for (const page of pages) {
    const cleanBody = stripUnsupportedBlocks(page.body);
    const outboundEntries = extractResolvedPageLinks(cleanBody, page, publicMap);
    page.outboundPages = outboundEntries.map((entry) => pageByRel.get(entry.publicRel)).filter(Boolean);

    for (const target of page.outboundPages) {
      if (!mentionsByPublicRel.has(target.publicRel)) mentionsByPublicRel.set(target.publicRel, []);
      mentionsByPublicRel.get(target.publicRel).push(page);
    }
  }

  for (const dir of OUTPUT_DIRS) cleanGeneratedDir(dir);
  const copiedAssetCount = copyGeneratedAssets(publicMap);

  const diagnostics = {
    unresolvedLinks: [],
    unresolvedEmbeds: []
  };

  for (const page of pages) {
    const mappedCharacterId = playerPageMap[page.publicRel];
    if (mappedCharacterId) {
      const assetPrefix = relativeHref(page.outputRel, 'index.html').replace(/index\.html$/, '');
      const html = applyTemplate(templates.base, {
        assetPrefix,
        breadcrumbJson: buildBreadcrumbJson(page, publicMap),
        content: buildPlayerRedirectPage(page, publicMap, mappedCharacterId),
        description: escapeAttribute(`${page.title} - Player sheet in the Eldoria Player Wiki`),
        navSection: navSectionForPage(page),
        title: escapeHtml(`${page.title} | Eldoria Player Wiki`),
        typeSlug: escapeAttribute(page.typeSlug)
      });
      writePage(page, html);
      continue;
    }

    let cleanBody = stripUnsupportedBlocks(page.body);
    cleanBody = stripLeadingTitle(cleanBody, page.title);
    const wikiMarkdown = replaceWikiLinks(cleanBody, page, publicMap, diagnostics);
    const bodyHtml = renderMarkdown(wikiMarkdown);
    const mentions = mentionsByPublicRel.get(page.publicRel) || [];
    const templateName = templateNameForType(page.type);

    const content = applyTemplate(templates[templateName], {
      body: bodyHtml,
      metaList: buildMetaList(page),
      metaTags: buildTagChips(page.tags),
      sidebar: buildSidebar(page, mentions),
      title: escapeHtml(page.title),
      type: escapeHtml(page.type),
      typeSlug: escapeAttribute(page.typeSlug),
      typeToneClass: toneForType(page.type),
      sourcePath: escapeHtml(`Public/${page.publicRel}`)
    });

    const assetPrefix = relativeHref(page.outputRel, 'index.html').replace(/index\.html$/, '');
    const html = applyTemplate(templates.base, {
      assetPrefix,
      breadcrumbJson: buildBreadcrumbJson(page, publicMap),
      content,
      description: escapeAttribute(`${page.title} - ${page.type} in the Eldoria Player Wiki`),
      navSection: navSectionForPage(page),
      title: escapeHtml(`${page.title} | Eldoria Player Wiki`),
      typeSlug: escapeAttribute(page.typeSlug)
    });

    writePage(page, html);
  }

  const generatedCounts = {
    world: pages.filter((page) => page.outputRel.startsWith('world/')).length,
    storylines: pages.filter((page) => page.outputRel.startsWith('storylines/')).length,
    players: pages.filter((page) => page.outputRel.startsWith('players/')).length
  };

  const unresolved = diagnostics.unresolvedLinks.length + diagnostics.unresolvedEmbeds.length;
  if (unresolved > 0) {
    console.warn(`Generated with ${unresolved} unresolved wiki references.`);
    diagnostics.unresolvedLinks.slice(0, 12).forEach((item) => {
      console.warn(`  link: ${item.source} -> ${item.target} (${item.reason})`);
    });
    diagnostics.unresolvedEmbeds.slice(0, 12).forEach((item) => {
      console.warn(`  embed: ${item.source} -> ${item.target} (${item.reason})`);
    });
  }

  console.log(`Generated ${pages.length} HTML pages.`);
  console.log(`  world: ${generatedCounts.world}`);
  console.log(`  storylines: ${generatedCounts.storylines}`);
  console.log(`  players: ${generatedCounts.players}`);
  console.log(`Copied ${copiedAssetCount} public assets.`);
}

if (require.main === module) {
  try {
    generate();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

