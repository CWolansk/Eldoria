const fs = require("fs");
const path = require("path");

const DOCS_DIR = __dirname;
const VAULT_ROOT = path.resolve(DOCS_DIR, "..");
const PUBLIC_WORLD_DIR = path.join(VAULT_ROOT, "Public", "World");
const OUTPUT_ROOT = path.join(DOCS_DIR, "tools", "world");
const MANIFEST_PATH = path.join(OUTPUT_ROOT, ".world-pages-manifest.json");
const CONFIG_PATH = path.join(DOCS_DIR, "world-pages.config.json");
const DATA_DIR = path.join(DOCS_DIR, "data");
