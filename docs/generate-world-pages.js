const DEFAULT_UNKNOWN_PAGE = "Unknown.md";
const LOCATION_REFERENCE_OUTPUT_REL = "tools/location-search/location-reference.html";
const NPC_REFERENCE_OUTPUT_REL = "tools/npc-search/npc-reference.html";
const WORLD_MAP_OUTPUT_REL = "tools/world-map.html";
const HIDDEN_MARKER_DESCRIPTION = "You have not visited or learned about this place yet.";

const IMAGE_EXTENSIONS = new Set([
  ".apng",
  ".avif",
  ".gif",
  ".jpeg",
  ".jpg",
  ".png",
  ".svg",
  ".webp"
]);

const SPECIAL_WORLD_FOLDERS = new Set(["events", "groups", "images", "items"]);

function toPosix(value) {
  return String(value || "").replace(/\\/g, "/");
}

function isInside(parentDir, targetPath) {
  const parent = path.resolve(parentDir);
  const target = path.resolve(targetPath);
  const relative = path.relative(parent, target);
  return relative === "" || (!!relative && !relative.startsWith("..") && !path.isAbsolute(relative));
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function sleepSync(milliseconds) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds);
}

function retryGeneratedFileOperation(operation, filePath) {
  let lastError = null;
  for (let attempt = 0; attempt < 4; attempt += 1) {
    try {
      return operation();
    } catch (error) {
      lastError = error;
      if (error.code !== "EPERM" && error.code !== "EACCES") throw error;
      if (fs.existsSync(filePath)) {
        try {
          fs.chmodSync(filePath, 0o666);
        } catch (_chmodError) {
          // Retry below; the next file operation will surface the useful error.
        }
      }
      sleepSync(50 * (attempt + 1));
    }
  }

  throw lastError;
}

function walkFiles(rootDir) {
  const results = [];
  if (!fs.existsSync(rootDir)) return results;

  for (const item of fs.readdirSync(rootDir, { withFileTypes: true })) {
    const fullPath = path.join(rootDir, item.name);
    if (item.isDirectory()) {
      results.push(...walkFiles(fullPath));
    } else if (item.isFile()) {
      results.push(fullPath);
    }
  }

  return results;
}

function slugifySegment(segment) {
  const slug = String(segment || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/['\u2018\u2019]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return slug || "untitled";
}

function stripKnownExtension(value) {
  const ext = path.posix.extname(toPosix(value));
  return ext ? value.slice(0, -ext.length) : value;
}

function slugifyFileName(fileName, forcedExtension = null) {
  const sourceExt = path.posix.extname(fileName);
  const ext = forcedExtension || sourceExt.toLowerCase();
  const base = sourceExt ? fileName.slice(0, -sourceExt.length) : fileName;
  return `${slugifySegment(base)}${ext}`;
}

function outputRelForWorldMarkdown(worldRel) {
  const parts = toPosix(worldRel).split("/").filter(Boolean);
  const fileName = parts.pop();
  return ["tools", "world", ...parts.map(slugifySegment), slugifyFileName(fileName, ".html")].join("/");
}

function outputRelForWorldAsset(worldRel) {
  const parts = toPosix(worldRel).split("/").filter(Boolean);
  const fileName = parts.pop();
  return ["tools", "world", ...parts.map(slugifySegment), slugifyFileName(fileName)].join("/");
}

function outputPathFromRel(outputRel) {
  return path.join(DOCS_DIR, ...toPosix(outputRel).split("/"));
}

function relativeHref(fromOutputRel, toOutputRel) {
  const fromDir = path.posix.dirname(toPosix(fromOutputRel));
  const rel = path.posix.relative(fromDir, toPosix(toOutputRel));
  return rel || path.posix.basename(toOutputRel);
}

function docsAssetPrefix(outputRel) {
  return relativeHref(outputRel, "index.html").replace(/index\.html$/, "");
}

function stripWorldPrefix(target) {
  return toPosix(target)
    .replace(/^\/+/, "")
    .replace(/^Public\/World\//i, "")
    .replace(/^World\//i, "")
    .replace(/^Public\//i, "");
}

function targetKey(value) {
  return stripKnownExtension(stripWorldPrefix(value)).toLowerCase();
}

function readJsonFileIfExists(filePath, fallback) {
  if (!fs.existsSync(filePath)) return fallback;

  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    throw new Error(`Unable to read ${path.relative(VAULT_ROOT, filePath)}: ${error.message}`);
  }
}

function stringArray(value) {
  if (!value) return [];
  if (Array.isArray(value)) return value.map((item) => String(item || "").trim()).filter(Boolean);
  return [String(value).trim()].filter(Boolean);
}

function readWorldPagesConfig() {
  const raw = readJsonFileIfExists(CONFIG_PATH, {});
  const visibility = raw.visibility || {};
  const worldMap = raw.worldMap || {};

  return {
    unknownPage: raw.unknownPage || DEFAULT_UNKNOWN_PAGE,
    visibility: {
      mode: String(visibility.mode || "blacklist").trim().toLowerCase(),
      whitelist: stringArray(visibility.whitelist),
      blacklist: stringArray(visibility.blacklist)
    },
    worldMap: {
      update: worldMap.update !== false,
      htmlPath: worldMap.htmlPath || WORLD_MAP_OUTPUT_REL,
      hiddenMarkerName: worldMap.hiddenMarkerName || "Unknown",
      hiddenMarkerDescription: worldMap.hiddenMarkerDescription || HIDDEN_MARKER_DESCRIPTION
    }
  };
}

function normalizeWorldSelector(value) {
  let normalized = toPosix(value)
    .trim()
    .replace(/^['"]|['"]$/g, "")
    .replace(/^\/+/, "");

  normalized = normalized
    .replace(/^docs\//i, "")
    .replace(/^tools\/world\//i, "")
    .replace(/^tools\//i, "")
    .replace(/^world\//i, "")
    .replace(/^Public\/World\//i, "")
    .replace(/^Public\//i, "");

  normalized = stripKnownExtension(normalized)
    .replace(/\/+$/g, "")
    .replace(/\/+/g, "/")
    .toLowerCase();

  return normalized;
}

function compactVisibilityKey(value) {
  return normalizeWorldSelector(value).replace(/[^a-z0-9]+/g, "");
}

function selectorVariants(value) {
  const normalized = normalizeWorldSelector(value);
  if (!normalized) return [];

  const variants = new Set([normalized]);
  if (normalized.endsWith("/**")) variants.add(normalized.slice(0, -3));
  if (normalized.endsWith("/*")) variants.add(normalized.slice(0, -2));

  const parts = normalized.split("/").filter(Boolean);
  if (parts.length > 1 && parts[parts.length - 1] === parts[parts.length - 2]) {
    variants.add(parts.slice(0, -1).join("/"));
  }

  variants.add(parts.map(slugifySegment).join("/"));
  return [...variants].filter(Boolean);
}

function pushIndex(map, key, value) {
  if (!map.has(key)) map.set(key, []);
  map.get(key).push(value);
}

function buildWorldPathMap() {
  const markdownPages = [];
  const assets = [];
  const pagesByNoExt = new Map();
  const pagesByStem = new Map();
  const assetsByNoExt = new Map();
  const assetsByStem = new Map();

  for (const fullPath of walkFiles(PUBLIC_WORLD_DIR)) {
    const worldRel = toPosix(path.relative(PUBLIC_WORLD_DIR, fullPath));
    const ext = path.extname(fullPath).toLowerCase();

    if (ext === ".md") {
      const entry = {
        fullPath,
        worldRel,
        publicRel: `World/${worldRel}`,
        outputRel: outputRelForWorldMarkdown(worldRel)
      };
      markdownPages.push(entry);
      pagesByNoExt.set(targetKey(worldRel), entry);
      pagesByNoExt.set(targetKey(`World/${worldRel}`), entry);
      pagesByNoExt.set(targetKey(`Public/World/${worldRel}`), entry);
      pushIndex(pagesByStem, path.basename(worldRel, ext).toLowerCase(), entry);
      continue;
    }

    if (IMAGE_EXTENSIONS.has(ext)) {
      const entry = {
        fullPath,
        worldRel,
        publicRel: `World/${worldRel}`,
        outputRel: outputRelForWorldAsset(worldRel)
      };
      assets.push(entry);
      assetsByNoExt.set(targetKey(worldRel), entry);
      assetsByNoExt.set(targetKey(`World/${worldRel}`), entry);
      assetsByNoExt.set(targetKey(`Public/World/${worldRel}`), entry);
      pushIndex(assetsByStem, path.basename(worldRel, ext).toLowerCase(), entry);
    }
  }

  markdownPages.sort((a, b) => a.worldRel.localeCompare(b.worldRel));
  assets.sort((a, b) => a.worldRel.localeCompare(b.worldRel));

  return {
    markdownPages,
    assets,
    pagesByNoExt,
    pagesByStem,
    assetsByNoExt,
    assetsByStem
  };
}

function stripQuotes(value) {
  return String(value || "").trim().replace(/^['"]|['"]$/g, "");
}

function parseScalar(rawValue) {
  const value = stripQuotes(rawValue);
  if (value === "") return "";
  if (value === "[]") return [];
  if (/^\[(.*)\]$/.test(value)) {
    return value
      .slice(1, -1)
      .split(",")
      .map((item) => stripQuotes(item))
      .filter(Boolean);
  }
  if (value === "true") return true;
  if (value === "false") return false;
  return value;
}

function parseFrontmatter(content) {
  const match = String(content || "").match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, body: String(content || "") };

  const data = {};
  let currentKey = null;

  for (const rawLine of match[1].split(/\r?\n/)) {
    const listMatch = rawLine.match(/^\s+-\s+(.*)$/);
    if (listMatch && currentKey) {
      if (!Array.isArray(data[currentKey])) data[currentKey] = [];
      data[currentKey].push(parseScalar(listMatch[1]));
      continue;
    }

    const kvMatch = rawLine.match(/^([A-Za-z0-9_-]+)\s*:\s*(.*)$/);
    if (kvMatch) {
      currentKey = kvMatch[1];
      data[currentKey] = parseScalar(kvMatch[2]);
    }
  }

  return {
    data,
    body: String(content || "").slice(match[0].length)
  };
}

function toArray(value) {
  if (!value) return [];
  return Array.isArray(value) ? value.filter(Boolean) : [value].filter(Boolean);
}

function titleFromBody(body) {
  const match = String(body || "").match(/^\s*#\s+(.+)$/m);
  return match ? match[1].trim() : "";
}

function inferType(worldRel, frontmatterType) {
  if (frontmatterType) return String(frontmatterType);

  const parts = toPosix(worldRel).split("/");
  const first = String(parts[0] || "").toLowerCase();
  const fileStem = path.posix.basename(worldRel, ".md");

  if (first === "groups") return "Organization";
  if (first === "events") return "Event";
  if (first === "items") return "Item";
  if (first === "images") return "Reference";
  if (parts.some((part) => part.toLowerCase() === "npcs")) return "NPC";
  if (parts.length === 2 && fileStem.toLowerCase() === parts[0].toLowerCase()) return "Region";
  if (parts.length >= 3 && fileStem.toLowerCase() === parts[1].toLowerCase()) return "Settlement";
  return "Location";
}

function inferRegion(worldRel, fm) {
  if (fm.region) return fm.region;
  const parts = toPosix(worldRel).split("/");
  const first = String(parts[0] || "").toLowerCase();
  return first && !SPECIAL_WORLD_FOLDERS.has(first) ? parts[0] : "";
}

function inferLocation(worldRel, fm, type) {
  if (fm.location) return fm.location;
  if (fm.headquarters) return fm.headquarters;

  const parts = toPosix(worldRel).split("/");
  const first = String(parts[0] || "").toLowerCase();
  if (SPECIAL_WORLD_FOLDERS.has(first) || type === "Region") return "";
  return parts.length > 2 ? parts[1] : "";
}

function buildPageContext(entry) {
  const raw = fs.readFileSync(entry.fullPath, "utf8");
  const parsed = parseFrontmatter(raw);
  const fm = parsed.data || {};
  const type = inferType(entry.worldRel, fm.type);
  const fallbackTitle = path.basename(entry.worldRel, ".md");
  const title = fm.name || titleFromBody(parsed.body) || fallbackTitle;

  return {
    ...entry,
    raw,
    body: parsed.body,
    fm,
    title,
    type,
    typeSlug: slugifySegment(type),
    region: inferRegion(entry.worldRel, fm),
    location: inferLocation(entry.worldRel, fm, type),
    tags: toArray(fm.tags)
  };
}

function pageVisibilityKeys(page) {
  if (page._visibilityKeys) return page._visibilityKeys;

  const keys = new Set();
  const add = (value) => {
    const normalized = normalizeWorldSelector(value);
    if (normalized) keys.add(normalized);
  };

  add(page.worldRel);
  add(page.publicRel);
  add(page.outputRel);
  add(page.title);
  add(page.type);
  add(page.region);
  add(page.location);
  page.tags.forEach(add);

  const noExt = normalizeWorldSelector(page.worldRel);
  const parts = noExt.split("/").filter(Boolean);
  for (let index = 1; index <= parts.length; index += 1) {
    add(parts.slice(0, index).join("/"));
  }

  if (parts.length > 1 && parts[parts.length - 1] === parts[parts.length - 2]) {
    add(parts.slice(0, -1).join("/"));
  }

  page._visibilityKeys = keys;
  page._compactVisibilityKeys = new Set([...keys].map(compactVisibilityKey).filter(Boolean));
  return keys;
}

function isExactFileSelector(selector) {
  const normalized = toPosix(selector).trim().replace(/^['"]|['"]$/g, "");
  return !normalized.includes("*") && path.posix.extname(normalized) !== "";
}

function selectorMatchesPage(selector, page) {
  if (isExactFileSelector(selector)) {
    const exactSelector = normalizeWorldSelector(selector);
    return [page.worldRel, page.publicRel, page.outputRel]
      .map(normalizeWorldSelector)
      .includes(exactSelector);
  }

  const keys = pageVisibilityKeys(page);
  const compactKeys = page._compactVisibilityKeys || new Set();

  return selectorVariants(selector).some((variant) => {
    const wildcard = /\/\*\*?$/.test(normalizeWorldSelector(selector));
    const compactVariant = compactVisibilityKey(variant);
    if (keys.has(variant) || compactKeys.has(compactVariant)) return true;
    if (!wildcard) return false;

    return [...keys].some((key) => key.startsWith(`${variant}/`));
  });
}

function findConfiguredPage(pages, selector) {
  const variants = selectorVariants(selector);
  const exact = pages.find((page) => {
    const sourceKeys = [
      normalizeWorldSelector(page.worldRel),
      normalizeWorldSelector(page.publicRel),
      normalizeWorldSelector(page.outputRel)
    ];
    const compactSourceKeys = sourceKeys.map(compactVisibilityKey);
    return variants.some((variant) => (
      sourceKeys.includes(variant) || compactSourceKeys.includes(compactVisibilityKey(variant))
    ));
  });

  if (exact) return exact;
  return pages.find((page) => selectorMatchesPage(selector, page)) || null;
}

function buildVisibilityState(pages, config) {
  const unknownPage = findConfiguredPage(pages, config.unknownPage)
    || findConfiguredPage(pages, DEFAULT_UNKNOWN_PAGE)
    || pages.find((page) => page.title.toLowerCase() === "unknown")
    || null;

  if (!unknownPage) {
    throw new Error("Unable to find the Unknown public page. Expected Public/World/Unknown.md.");
  }

  const mode = config.visibility.mode === "whitelist" ? "whitelist" : "blacklist";
  const whitelist = config.visibility.whitelist;
  const blacklist = config.visibility.blacklist;
  const visibleWorldRels = new Set();
  const hiddenWorldRels = new Set();

  for (const page of pages) {
    const isUnknownPage = page.worldRel === unknownPage.worldRel;
    const isBlacklisted = !isUnknownPage && blacklist.some((selector) => selectorMatchesPage(selector, page));
    const isWhitelisted = isUnknownPage || whitelist.some((selector) => selectorMatchesPage(selector, page));
    const visible = isUnknownPage || (!isBlacklisted && (mode === "blacklist" || isWhitelisted));

    page.isVisibleToPlayers = visible;
    page.visibilityReason = visible
      ? (isUnknownPage ? "unknown-page" : (mode === "whitelist" ? "whitelist" : "default-visible"))
      : (isBlacklisted ? "blacklist" : "not-whitelisted");

    if (visible) visibleWorldRels.add(page.worldRel);
    else hiddenWorldRels.add(page.worldRel);
  }

  return {
    mode,
    whitelist,
    blacklist,
    unknownPage,
    visibleWorldRels,
    hiddenWorldRels,
    isVisible(pageOrEntry) {
      return !!pageOrEntry && visibleWorldRels.has(pageOrEntry.worldRel);
    },
    isHidden(pageOrEntry) {
      return !!pageOrEntry && hiddenWorldRels.has(pageOrEntry.worldRel);
    }
  };
}

function buildAssetVisibilityContext(asset) {
  const type = "Asset";
  const fallbackTitle = path.basename(asset.worldRel, path.extname(asset.worldRel));
  return {
    ...asset,
    title: fallbackTitle,
    type,
    region: inferRegion(asset.worldRel, {}),
    location: inferLocation(asset.worldRel, {}, type),
    tags: []
  };
}

function isAssetVisible(asset, config) {
  const context = buildAssetVisibilityContext(asset);
  const mode = config.visibility.mode === "whitelist" ? "whitelist" : "blacklist";
  const isBlacklisted = config.visibility.blacklist.some((selector) => selectorMatchesPage(selector, context));
  const isWhitelisted = config.visibility.whitelist.some((selector) => selectorMatchesPage(selector, context));
  return !isBlacklisted && (mode === "blacklist" || isWhitelisted);
}

function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeAttribute(value) {
  return escapeHtml(value).replace(/`/g, "&#96;");
}

function markdownEscapeText(value) {
  return String(value || "").replace(/[[\]]/g, "\\$&");
}

function markdownEscapeUrl(value) {
  return String(value || "").replace(/\)/g, "%29");
}

function splitWikiTarget(rawTarget) {
  const [targetPart, ...displayParts] = String(rawTarget || "").split("|");
  const display = displayParts.join("|").trim();
  const [pathPart, ...anchorParts] = targetPart.trim().split("#");

  return {
    target: pathPart.trim(),
    anchor: anchorParts.join("#").trim(),
    display
  };
}

function displayNameForTarget(target) {
  const withoutAnchor = String(target || "").split("#")[0];
  const last = toPosix(withoutAnchor).split("/").filter(Boolean).pop() || withoutAnchor;
  return stripKnownExtension(last);
}

function isImageTarget(target) {
  return IMAGE_EXTENSIONS.has(path.posix.extname(toPosix(target)).toLowerCase());
}

function anchorSlug(anchor) {
  return slugifySegment(anchor);
}

function preferClosestByPath(candidates, context) {
  if (!candidates || candidates.length === 0) return null;
  if (candidates.length === 1) return candidates[0];

  const contextParts = toPosix(context.worldRel).split("/").slice(0, -1);
  let best = candidates[0];
  let bestScore = -1;

  for (const candidate of candidates) {
    const candidateParts = toPosix(candidate.worldRel).split("/").slice(0, -1);
    let score = 0;
    while (
      score < contextParts.length &&
      score < candidateParts.length &&
      contextParts[score].toLowerCase() === candidateParts[score].toLowerCase()
    ) {
      score += 1;
    }

    if (score > bestScore) {
      best = candidate;
      bestScore = score;
    }
  }

  return best;
}

function resolveFromMap(target, context, worldMap, kind) {
  const normalizedTarget = stripWorldPrefix(target);
  const key = targetKey(normalizedTarget);
  const directMap = kind === "asset" ? worldMap.assetsByNoExt : worldMap.pagesByNoExt;
  const stemMap = kind === "asset" ? worldMap.assetsByStem : worldMap.pagesByStem;

  if (directMap.has(key)) return directMap.get(key);

  const contextDir = toPosix(context.worldRel).split("/").slice(0, -1).join("/");
  if (contextDir && !normalizedTarget.includes("/")) {
    const localKey = targetKey(`${contextDir}/${normalizedTarget}`);
    if (directMap.has(localKey)) return directMap.get(localKey);
  }

  const targetParts = normalizedTarget.split("/").filter(Boolean);
  if (targetParts.length > 1) {
    const last = targetParts[targetParts.length - 1];
    const previous = targetParts[targetParts.length - 2];
    if (last.toLowerCase() === previous.toLowerCase()) {
      const foldedKey = targetKey(targetParts.slice(0, -1).join("/"));
      if (directMap.has(foldedKey)) return directMap.get(foldedKey);
    }
  }

  if (normalizedTarget.includes("/")) {
    const targetParent = path.posix.dirname(stripKnownExtension(normalizedTarget)).toLowerCase();
    const targetStem = stripKnownExtension(path.posix.basename(normalizedTarget)).toLowerCase();
    const entries = kind === "asset" ? worldMap.assets : worldMap.markdownPages;
    const candidates = entries.filter((entry) => {
      const entryParent = path.posix.dirname(stripKnownExtension(entry.worldRel)).toLowerCase();
      const entryStem = stripKnownExtension(path.posix.basename(entry.worldRel)).toLowerCase();
      return entryParent === targetParent && (entryStem.includes(targetStem) || targetStem.includes(entryStem));
    });
    const closest = preferClosestByPath(candidates, context);
    if (closest) return closest;
  }

  if (!normalizedTarget.includes("/")) {
    const stem = stripKnownExtension(normalizedTarget).toLowerCase();
    return preferClosestByPath(stemMap.get(stem), context);
  }

  return null;
}

function resolveWikiTarget(rawTarget, context, worldMap, visibility = null) {
  const parts = splitWikiTarget(rawTarget);
  const display = parts.display || displayNameForTarget(parts.target || parts.anchor);

  if (!parts.target && parts.anchor) {
    return {
      kind: "anchor",
      display,
      href: `#${anchorSlug(parts.anchor)}`
    };
  }

  if (/^(private|private\/|private\\)/i.test(parts.target)) {
    return { kind: "private", display, target: parts.target };
  }

  if (isImageTarget(parts.target)) {
    const asset = resolveFromMap(parts.target, context, worldMap, "asset");
    if (!asset) return { kind: "missing-asset", display, target: parts.target };
    return {
      kind: "asset",
      display,
      target: parts.target,
      asset,
      href: relativeHref(context.outputRel, asset.outputRel)
    };
  }

  const page = resolveFromMap(parts.target, context, worldMap, "page");
  if (!page) return { kind: "missing-page", display, target: parts.target };
  if (visibility && visibility.isHidden(page)) {
    return {
      kind: "page",
      display: visibility.unknownPage.title,
      target: parts.target,
      page: visibility.unknownPage,
      href: relativeHref(context.outputRel, visibility.unknownPage.outputRel)
    };
  }

  return {
    kind: "page",
    display,
    target: parts.target,
    page,
    href: `${relativeHref(context.outputRel, page.outputRel)}${parts.anchor ? `#${anchorSlug(parts.anchor)}` : ""}`
  };
}

function replaceWikiLinks(markdown, context, worldMap, diagnostics, visibility = null) {
  let rendered = String(markdown || "").replace(/!\[\[([^\]]+)\]\]/g, (_match, rawTarget) => {
    const resolved = resolveWikiTarget(rawTarget, context, worldMap, visibility);
    if (resolved.kind === "asset") {
      return `![${markdownEscapeText(resolved.display)}](${markdownEscapeUrl(resolved.href)})`;
    }

    diagnostics.unresolvedEmbeds.push({
      source: context.worldRel,
      target: rawTarget,
      reason: resolved.kind
    });
    return `_${markdownEscapeText(`Missing embed: ${resolved.display}`)}_`;
  });

  rendered = rendered.replace(/\[\[([^\]]+)\]\]/g, (_match, rawTarget) => {
    const resolved = resolveWikiTarget(rawTarget, context, worldMap, visibility);
    if (resolved.kind === "page" || resolved.kind === "anchor") {
      return `[${markdownEscapeText(resolved.display)}](${markdownEscapeUrl(resolved.href)})`;
    }

    diagnostics.unresolvedLinks.push({
      source: context.worldRel,
      target: rawTarget,
      reason: resolved.kind
    });
    return markdownEscapeText(resolved.display);
  });

  return rendered;
}

function extractResolvedPageLinks(markdown, context, worldMap, visibility = null) {
  const links = [];
  const re = /!?\[\[([^\]]+)\]\]/g;
  let match;

  while ((match = re.exec(markdown)) !== null) {
    if (match[0].startsWith("!")) continue;
    const resolved = resolveWikiTarget(match[1], context, worldMap, visibility);
    if (resolved.kind === "page" && resolved.page.worldRel !== context.worldRel) {
      links.push(resolved.page);
    }
  }

  return [...new Map(links.map((entry) => [entry.worldRel, entry])).values()];
}

function findForbiddenPrivateRefs(markdown, sourceLabel) {
  const problems = [];
  const wikiRe = /!?\[\[([^\]]+)\]\]/g;
  const mdLinkRe = /\[[^\]]+\]\(([^)]+)\)/g;
  let match;

  while ((match = wikiRe.exec(markdown)) !== null) {
    const target = splitWikiTarget(match[1]).target;
    if (/(^|[\\/])Private([\\/]|$)/i.test(toPosix(target))) {
      problems.push(`${sourceLabel}: wiki-link points at ${target}`);
    }
  }

  while ((match = mdLinkRe.exec(markdown)) !== null) {
    if (/(^|[\\/])Private([\\/]|$)/i.test(toPosix(match[1]))) {
      problems.push(`${sourceLabel}: markdown link points at ${match[1]}`);
    }
  }

  return problems;
}

function assertNoPrivateSourceLinks(entries) {
  const problems = [];
  for (const entry of entries) {
    const content = fs.readFileSync(entry.fullPath, "utf8");
    problems.push(...findForbiddenPrivateRefs(content, entry.worldRel));
  }

  if (problems.length > 0) {
    throw new Error(`Private references found in Public/World markdown:\n${problems.join("\n")}`);
  }
}

function stripUnsupportedBlocks(markdown) {
  let body = String(markdown || "");
  body = body.replace(/```(?:dataview|dataviewjs|custom-frames)[\s\S]*?```/gi, "");
  body = body.replace(/\n{3,}/g, "\n\n");
  return body.trim();
}

function stripLeadingTitle(markdown, title) {
  const lines = String(markdown || "").split(/\r?\n/);
  const firstContentIndex = lines.findIndex((line) => line.trim() !== "");
  if (firstContentIndex < 0) return markdown;

  const heading = lines[firstContentIndex].match(/^#\s+(.+)$/);
  if (heading && heading[1].trim().toLowerCase() === String(title || "").trim().toLowerCase()) {
    lines.splice(firstContentIndex, 1);
  }

  return lines.join("\n").trim();
}

function inlineMarkdown(value) {
  const placeholders = [];
  let text = String(value || "");

  text = text.replace(/`([^`]+)`/g, (_match, code) => {
    const token = `@@CODE${placeholders.length}@@`;
    placeholders.push(`<code>${escapeHtml(code)}</code>`);
    return token;
  });

  text = escapeHtml(text);

  text = text.replace(/!\[([^\]]*)\]\(([^)]+)\)/g, (_match, alt, href) => {
    return `<img class="generated-inline-image" src="${escapeAttribute(href)}" alt="${escapeAttribute(alt)}">`;
  });
  text = text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_match, label, href) => {
    return `<a href="${escapeAttribute(href)}">${label}</a>`;
  });
  text = text.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  text = text.replace(/\*([^*]+)\*/g, "<em>$1</em>");

  placeholders.forEach((html, index) => {
    text = text.replace(`@@CODE${index}@@`, html);
  });

  return text;
}

function renderTable(lines) {
  const rows = lines
    .filter((_line, index) => index !== 1)
    .map((line) => line.trim().replace(/^\||\|$/g, "").split("|").map((cell) => cell.trim()));
  const [headers, ...bodyRows] = rows;

  return [
    '<div class="data-table-wrap">',
    '<table class="data-table">',
    "<thead><tr>",
    headers.map((header) => `<th>${inlineMarkdown(header)}</th>`).join(""),
    "</tr></thead>",
    "<tbody>",
    bodyRows.map((row) => `<tr>${row.map((cell) => `<td>${inlineMarkdown(cell)}</td>`).join("")}</tr>`).join("\n"),
    "</tbody>",
    "</table>",
    "</div>"
  ].join("");
}

function collectUntil(lines, start, predicate) {
  const collected = [];
  let index = start;
  while (index < lines.length && predicate(lines[index], index)) {
    collected.push(lines[index]);
    index += 1;
  }
  return { collected, nextIndex: index };
}

function renderMarkdown(markdown) {
  const lines = String(markdown || "").replace(/\r\n/g, "\n").split("\n");
  const html = [];
  let index = 0;

  while (index < lines.length) {
    const line = lines[index];
    const trimmed = line.trim();

    if (!trimmed) {
      index += 1;
      continue;
    }

    if (/^```/.test(trimmed)) {
      const language = trimmed.replace(/^```/, "").trim();
      const collected = [];
      index += 1;
      while (index < lines.length && !/^```/.test(lines[index].trim())) {
        collected.push(lines[index]);
        index += 1;
      }
      index += 1;
      html.push(`<pre class="code-block"><code${language ? ` class="language-${escapeAttribute(language)}"` : ""}>${escapeHtml(collected.join("\n"))}</code></pre>`);
      continue;
    }

    if (/^#{1,6}\s+/.test(trimmed)) {
      const [, marks, label] = trimmed.match(/^(#{1,6})\s+(.+)$/);
      const level = Math.min(marks.length, 3);
      html.push(`<h${level} id="${escapeAttribute(slugifySegment(label))}">${inlineMarkdown(label)}</h${level}>`);
      index += 1;
      continue;
    }

    if (/^---+$/.test(trimmed)) {
      html.push("<hr>");
      index += 1;
      continue;
    }

    if (/^\|.*\|$/.test(trimmed) && lines[index + 1] && /^\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?$/.test(lines[index + 1].trim())) {
      const table = collectUntil(lines, index, (candidate) => /^\|.*\|$/.test(candidate.trim()));
      html.push(renderTable(table.collected));
      index = table.nextIndex;
      continue;
    }

    if (/^>\s?/.test(trimmed)) {
      const block = collectUntil(lines, index, (candidate) => /^>\s?/.test(candidate.trim()));
      const content = block.collected.map((candidate) => candidate.replace(/^>\s?/, "")).join("\n");
      html.push(`<blockquote>${renderMarkdown(content)}</blockquote>`);
      index = block.nextIndex;
      continue;
    }

    if (/^[-*]\s+/.test(trimmed)) {
      const list = collectUntil(lines, index, (candidate) => /^[-*]\s+/.test(candidate.trim()));
      html.push(`<ul>${list.collected.map((item) => `<li>${inlineMarkdown(item.trim().replace(/^[-*]\s+/, ""))}</li>`).join("")}</ul>`);
      index = list.nextIndex;
      continue;
    }

    if (/^\d+\.\s+/.test(trimmed)) {
      const list = collectUntil(lines, index, (candidate) => /^\d+\.\s+/.test(candidate.trim()));
      html.push(`<ol>${list.collected.map((item) => `<li>${inlineMarkdown(item.trim().replace(/^\d+\.\s+/, ""))}</li>`).join("")}</ol>`);
      index = list.nextIndex;
      continue;
    }

    const paragraph = collectUntil(lines, index, (candidate) => {
      const t = candidate.trim();
      return t && !/^(```|#{1,6}\s+|---+$|>\s?|[-*]\s+|\d+\.\s+|\|.*\|$)/.test(t);
    });
    html.push(`<p>${inlineMarkdown(paragraph.collected.map((item) => item.trim()).join(" "))}</p>`);
    index = paragraph.nextIndex;
  }

  return html.join("\n");
}

function toneForType(type) {
  const key = String(type || "").toLowerCase();
  if (key === "npc") return "npc-card";
  if (key === "settlement") return "settlement-card";
  if (key === "store" || key === "shop") return "shop-card";
  if (key === "location" || key === "region") return "location-card";
  return "";
}

