function fileNameFromOutput(page) {
  return path.posix.basename(page.outputRel);
}

function settlementBranchKey(page) {
  const parts = stripKnownExtension(toPosix(page.worldRel)).split("/").filter(Boolean);
  if (parts.length < 3) return "";
  return `${parts[0].toLowerCase()}/${parts[1].toLowerCase()}`;
}

function hasWorldPathSegment(page, segment) {
  const expected = String(segment || "").toLowerCase();
  return stripKnownExtension(toPosix(page.worldRel))
    .split("/")
    .some((part) => part.toLowerCase() === expected);
}

function isTopLevelPlacePage(page) {
  if (isSpecialWorldPage(page) || hasWorldPathSegment(page, "npcs")) return false;
  const parts = stripKnownExtension(toPosix(page.worldRel)).split("/").filter(Boolean);
  if (parts.length < 3) return false;
  return parts[1].toLowerCase() === parts[parts.length - 1].toLowerCase();
}

function regionBaseHrefFromPage(referenceOutputRel, page) {
  const parts = toPosix(page.outputRel).split("/").filter(Boolean);
  const regionDir = parts.slice(0, 3).join("/");
  const fromDir = path.posix.dirname(referenceOutputRel);
  const rel = path.posix.relative(fromDir, regionDir);
  return `${rel || "."}/`;
}

function buildLocationIndex(pages) {
  const index = {};
  const placesByBranch = new Map();
  const visiblePages = pages.filter((page) => page.isVisibleToPlayers && !isSpecialWorldPage(page));

  for (const page of visiblePages) {
    if (!isTopLevelPlacePage(page)) continue;
    const branch = settlementBranchKey(page);
    if (!branch) continue;

    const regionName = page.region || toPosix(page.worldRel).split("/")[0] || "Unknown";
    if (!index[regionName]) {
      index[regionName] = {
        basePath: regionBaseHrefFromPage(LOCATION_REFERENCE_OUTPUT_REL, page),
        locations: {}
      };
    }

    index[regionName].locations[page.title] = {
      file: fileNameFromOutput(page),
      href: hrefFromReferencePage(LOCATION_REFERENCE_OUTPUT_REL, page),
      subLocations: []
    };
    placesByBranch.set(branch, { regionName, placeName: page.title });
  }

  for (const page of visiblePages) {
    const type = String(page.type).toLowerCase();
    if (type === "region" || type === "npc" || hasWorldPathSegment(page, "npcs") || isTopLevelPlacePage(page)) continue;

    const branch = settlementBranchKey(page);
    const place = placesByBranch.get(branch);
    if (!place) continue;

    index[place.regionName].locations[place.placeName].subLocations.push({
      name: page.title,
      file: fileNameFromOutput(page),
      href: hrefFromReferencePage(LOCATION_REFERENCE_OUTPUT_REL, page)
    });
  }

  for (const regionData of Object.values(index)) {
    const sortedLocations = {};
    for (const [name, location] of Object.entries(regionData.locations).sort(([a], [b]) => a.localeCompare(b))) {
      location.subLocations.sort((a, b) => a.name.localeCompare(b.name));
      sortedLocations[name] = location;
    }
    regionData.locations = sortedLocations;
  }

  return Object.fromEntries(Object.entries(index).sort(([a], [b]) => a.localeCompare(b)));
}

function buildNpcIndex(pages) {
  const index = {};
  const npcs = pages
    .filter((page) => page.isVisibleToPlayers && String(page.type).toLowerCase() === "npc")
    .sort((a, b) => a.title.localeCompare(b.title));

  for (const page of npcs) {
    const regionName = page.region || "Unknown";
    const locationName = page.location || "Unknown";

    if (!index[regionName]) index[regionName] = {};
    if (!index[regionName][locationName]) {
      index[regionName][locationName] = {
        basePath: path.posix.dirname(hrefFromReferencePage(NPC_REFERENCE_OUTPUT_REL, page)).replace(/\/?$/, "/"),
        npcs: []
      };
    }

    index[regionName][locationName].npcs.push({
      name: page.title,
      file: fileNameFromOutput(page),
      href: hrefFromReferencePage(NPC_REFERENCE_OUTPUT_REL, page)
    });
  }

  for (const regionData of Object.values(index)) {
    for (const locationData of Object.values(regionData)) {
      locationData.npcs.sort((a, b) => a.name.localeCompare(b.name));
    }
  }

  return Object.fromEntries(Object.entries(index).sort(([a], [b]) => a.localeCompare(b)));
}

